import { createHash } from "node:crypto";
import { esc } from "./svg.mjs";

export function hash8(content) {
  return createHash("sha256").update(content).digest("hex").slice(0, 8);
}

function picture(name, hashes, alt) {
  const url = theme => {
    const hash = hashes[`${name}-${theme}`];
    if (!hash) throw new Error(`missing hash for ${name}-${theme}`);
    return `assets/${name}-${theme}.svg?v=${hash}`;
  };
  return [
    "<picture>",
    `  <source media="(prefers-color-scheme: dark)" srcset="${url("dark")}">`,
    `  <source media="(prefers-color-scheme: light)" srcset="${url("light")}">`,
    `  <img alt="${esc(alt)}" src="${url("dark")}" width="100%">`,
    "</picture>",
  ].join("\n");
}

export function renderReadme(profile, { hashes, alts }) {
  const r = profile.readme;
  const projects = r.projects.map(pr =>
    `- [${pr.name}](${pr.url}): ${pr.line}` + (pr.extra ? ` [${pr.extra[0]}](${pr.extra[1]}).` : ""));
  return [
    "<!-- Generated by scripts/build.mjs from data/profile.json. Edit that file, not this one. -->",
    "",
    picture("session", hashes, alts.session),
    "",
    picture("fetch", hashes, alts.fetch),
    "",
    r.intro,
    "",
    r.projectsHeading,
    "",
    ...projects,
    "",
    r.after,
    "",
    r.outro,
    "",
  ].join("\n");
}
