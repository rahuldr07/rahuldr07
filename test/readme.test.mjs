import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { hash8, renderReadme } from "../scripts/lib/readme.mjs";

const profile = JSON.parse(readFileSync("data/profile.json", "utf8"));
const hashes = { "session-dark": "aaaaaaaa", "session-light": "bbbbbbbb", "fetch-dark": "cccccccc", "fetch-light": "dddddddd" };

test("hash8 is 8 hex chars and stable", () => {
  assert.equal(hash8("x"), hash8("x"));
  assert.match(hash8("x"), /^[0-9a-f]{8}$/);
});

test("readme has two themed pictures with alt text and versioned urls", () => {
  const md = renderReadme(profile, { hashes, alts: { session: `say "hi"`, fetch: "card" } });
  assert.ok(md.startsWith("<!-- Generated by scripts/build.mjs from data/profile.json. Edit that file, not this one. -->\n\n"));
  assert.equal(md.match(/<picture>/g).length, 2);
  assert.match(md, /media="\(prefers-color-scheme: dark\)" srcset="assets\/session-dark\.svg\?v=aaaaaaaa"/);
  assert.match(md, /media="\(prefers-color-scheme: light\)" srcset="assets\/fetch-light\.svg\?v=dddddddd"/);
  assert.match(md, /alt="say &quot;hi&quot;"/);
  assert.match(md, /\[go-calc\]\(https:\/\/github\.com\/rahuldr07\/go-calc\)/);
  assert.match(md, /\[Try it\]\(https:\/\/calc\.dileeshrahul\.dev\/\)/);
});

test("a missing hash is an error, not a silent ?v=undefined", () => {
  assert.throws(() => renderReadme(profile, { hashes: { "session-dark": "aaaaaaaa" }, alts: { session: "s", fetch: "f" } }), /missing hash/);
});
